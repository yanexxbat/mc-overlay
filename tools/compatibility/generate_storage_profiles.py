"""Audit loaded-container traversal against checksum-verified cached game jars."""
import hashlib,json,re,sys
from pathlib import Path
from classfile import NamedJar
from generate_profiles import namespace_map,namespace_method,VERSIONS,ROOT

C={'level':'net/minecraft/client/multiplayer/ClientLevel',
   'source':'net/minecraft/client/multiplayer/ClientChunkCache',
   'storage':'net/minecraft/client/multiplayer/ClientChunkCache$Storage',
   'chunk':'net/minecraft/world/level/chunk/LevelChunk','pos':'net/minecraft/core/BlockPos'}
S=[('source','level','getChunkSource','()L'+C['source']+';','methods'),
   ('storage','source','storage','L'+C['storage']+';','fields'),
   ('chunks','storage','chunks','Ljava/util/concurrent/atomic/AtomicReferenceArray;','fields'),
   ('entities','chunk','getBlockEntities','()Ljava/util/Map;','methods')]
S += [(axis,'pos','get'+axis.upper(),'()I','methods') for axis in ('x','y','z')]

def generate(cache):
    for name,entry in json.loads(Path(__file__).with_name('mapping_inputs.json').read_text()).items():
        if hashlib.sha256((cache/name).read_bytes()).hexdigest()!=entry['sha256']: raise ValueError('Mapping checksum mismatch: '+name)
    rows=[]
    for version in VERSIONS:
        meta=json.loads((cache/(version+'.json')).read_text(encoding='utf-8-sig'))
        for kind,suffix in [('client','.jar'),('client_mappings','-mappings.txt')]:
            if kind in meta['downloads'] and hashlib.sha1((cache/(version+suffix)).read_bytes()).hexdigest()!=meta['downloads'][kind]['sha1']:
                raise ValueError('Client checksum mismatch: '+version)
        jar=NamedJar(cache,version); resolved=[]
        for key,role,name,desc,kind in S:
            found=next(((owner,m) for owner,m in jar.members(C[role],kind) if m['name']==name and m['descriptor']==desc),None)
            if not found or found[1]['flags']&8: raise ValueError('Storage member missing: '+version+' '+key)
            resolved.append((key,role,*found,kind))
        spaces=['mojmap']+([] if version=='26.2' else ['vanilla','intermediary'])+(['forge-srg'] if version=='1.20.1' else [])
        for ns in spaces:
            classes,fields,methods=namespace_map(cache,version,ns)
            def cls(name):
                raw=jar.mapping.get(name,{}).get('obf',name)
                return raw if ns=='vanilla' else classes.get(raw,raw) if ns=='intermediary' else name
            def desc(value): return re.sub(r'L([^;]+);',lambda m:'L'+cls(m[1])+';',value)
            row={'id':ns+'-'+version,'classes':{key:cls(value) for key,value in C.items()},'members':{},'owners':{},'kinds':{}}
            for key,role,owner,m,kind in resolved:
                name=m['name']; raw=jar.mapping.get(owner,{}).get('obf',owner)
                if ns=='vanilla': name=m['raw_name']
                elif ns in ('intermediary','forge-srg'):
                    name=namespace_method(jar,owner,m['raw_name'],m['raw_descriptor'],methods) if kind=='methods' else fields.get((raw,m['raw_name'],None if ns=='forge-srg' else m['raw_descriptor']),m['raw_name'])
                row['members'][key]=[name,desc(m['descriptor'])];row['owners'][key]=cls(C[role]);row['kinds'][key]=kind
            rows.append(row)
    header=['// Generated by generate_storage_profiles.py from audited cached classes.','#pragma once','#include "mappings.hpp"','#include <string_view>',
      'namespace mcov::agent {','struct StorageProfile { const char* id; const char* chunkClass; const char* posClass; mcov::mappings::Member source,storage,chunks,entities,x,y,z; };',
      'inline constexpr StorageProfile kStorageProfiles[]={']
    for row in rows:
        header.append('    {'+','.join(map(json.dumps,[row['id'],row['classes']['chunk'],row['classes']['pos']]))+','+','.join('{'+','.join(map(json.dumps,row['members'][key]))+'}' for key,_,_,_,_ in S)+'},')
    header += ['};','inline const StorageProfile* StorageMapping(std::string_view id) { for(const auto& p:kStorageProfiles) if(id==p.id) return &p; return nullptr; }','}']
    (ROOT/'src/agent/storage_profiles.hpp').write_text('\n'.join(header)+'\n',encoding='utf-8',newline='\n')
    Path(__file__).with_name('storage_profiles.json').write_text(json.dumps(rows,indent=2)+'\n',encoding='utf-8',newline='\n')
    print(f'Audited {len(rows)} storage profiles / {len(S)} members; no block-volume traversal required')

if __name__=='__main__': generate(Path(sys.argv[1]))
